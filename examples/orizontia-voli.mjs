/**
 * Έτοιμο μάθημα: «Οριζόντια βολή» για τη Φυσική της Β΄ Λυκείου.
 * Φτιάχνει το examples/Οριζόντια βολή - Β Λυκείου.json, που ανοίγει στο PrismaBoard με ☰ → «Άνοιγμα…» ως νέο μάθημα.
 *   node examples/orizontia-voli.mjs
 * Κάθε σελίδα είναι γραμμένη με τη σειρά που διδάσκεται: με «Όργανα → Παρουσίαση → Αναπαραγωγή» ξετυλίγεται
 * βήμα βήμα (⏸ παύση, ⏭ ένα βήμα τη φορά). Οι συντεταγμένες είναι για οθόνη περίπου 1600 × 900· σε μικρότερη,
 * ☰ → «Προσαρμογή προβολής».
 */
import { writeFileSync } from 'node:fs';

const OUT = 'examples/Οριζόντια βολή - Β Λυκείου.json';
const INK = '#111111', BLUE = '#2563eb', RED = '#dc2626', GREEN = '#16a34a', GRAY = '#4b5563', HL = '#facc15';

let n = 0;
const id = () => `ov${++n}`;
const T = (x, y, text, size = 30, color = INK) => ({ kind: 'text', id: id(), x, y, text, size, color });
const shape = (shape, x0, y0, x1, y1, color = INK, width = 4, more = {}) => ({ kind: 'shape', id: id(), shape, x0, y0, x1, y1, color, width, ...more });
const arrow = (x0, y0, x1, y1, color = INK, width = 4) => shape('arrow', x0, y0, x1, y1, color, width);
const line = (x0, y0, x1, y1, color = INK, width = 4, dash = false) => shape('line', x0, y0, x1, y1, color, width, dash ? { dash: true } : {});
const ball = (x, y, r, color) => shape('ellipse', x - r, y - r, x + r, y + r, color, 4);
const stroke = (pts, color = INK, width = 5, hl = false) => ({ kind: 'stroke', id: id(), pts: pts.map(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10]), color, width, hl });
/** Χέρι που τραβά γραμμή: λίγο «ζωντανή», όχι τελείως ίσια. */
const hand = (x0, y0, x1, y1, color, width = 5, hl = false) => {
  const pts = [];
  for (let i = 0; i <= 24; i++) {
    const u = i / 24;
    pts.push([x0 + (x1 - x0) * u, y0 + (y1 - y0) * u + Math.sin(u * 7) * 1.6]);
  }
  return stroke(pts, color, width, hl);
};
const curve = (f, n, color, width = 5) => stroke(Array.from({ length: n + 1 }, (_, i) => f(i / n)), color, width);
/** Υπογραμμιστής πάνω σε κείμενο μεγέθους `size` που ξεκινά στο y (ο πίνακας τον ζωγραφίζει 4 φορές πιο χοντρό). */
const mark = (x0, x1, y, size) => hand(x0, y + size * 0.62, x1, y + size * 0.62, HL, size * 0.28, true);
/** Τίτλος σελίδας με υπογράμμιση «με το χέρι». */
const title = (text, w) => [T(80, 70, text, 50, BLUE), hand(82, 138, 82 + w, 140, BLUE, 5)];
// όλη η σελίδα λίγο πιο κάτω, ώστε ο τίτλος να μην ακουμπά τη μπάρα με το όνομα του μαθήματος
const page = (...items) => ({ items: items.flat(), view: { x: 0, y: 25, k: 1 } });

